#!/usr/bin/env python3
"""Generate the cabinet avatars from docs/images/avatars/*.png.

Outputs (all inside the package):
  src/avatars/<key>.png        128x128, downscaled from the 512x512 originals
  src/avatars.js               ESM module exporting the data URLs
  client.js                    the GENERATED avatars region is rewritten in place

A missing original becomes a solid tint placeholder data URL and is listed in
AVATAR_PLACEHOLDERS (TODO: replace once the final art lands), so the panel never
ships a broken image.

Why client.js carries the data inline: the browser module table cannot resolve a
relative require (dsh-client-modules/lib/client.js:834-842 only answers platform
seed words, materialised modules and registered package factories) and package
chunks must be named client.<name>.js at the package root (:845-846), so
src/avatars.js is the canonical source and client.js is regenerated from it by
this script — never edit either by hand.

Re-run after new avatar art:  python3 src/build_avatars.py
"""

from __future__ import annotations

import base64
import io
import re
import sys
from pathlib import Path

from PIL import Image

PKG = Path(__file__).resolve().parent.parent
ORIGINALS = PKG / "docs" / "images" / "avatars"
OUT_DIR = PKG / "src" / "avatars"
AVATARS_JS = PKG / "src" / "avatars.js"
CLIENT_JS = PKG / "client.js"

SIZE = 128
KEYS = ["lead", "hanlin", "works", "dali", "yushi"]
# 首辅明黄 / 编修青 / 主事赤 / 评事玄 / 御史绯
PLACEHOLDER_COLOR = {
    "lead": "#F5C518",
    "hanlin": "#12A5A5",
    "works": "#D93A2B",
    "dali": "#23262B",
    "yushi": "#C7304A",
}

REGION_START = "// #region avatars — GENERATED by src/build_avatars.py (do not edit by hand)"
REGION_END = "// #endregion avatars"


def square_resize(path: Path) -> Image.Image:
    """Open, centre-crop to a square, then resize to SIZE x SIZE."""
    with Image.open(path) as im:
        im = im.convert("RGBA") if im.mode in ("P", "LA", "RGBA") else im.convert("RGB")
        width, height = im.size
        side = min(width, height)
        left = (width - side) // 2
        top = (height - side) // 2
        im = im.crop((left, top, left + side, top + side))
        if side != SIZE:
            im = im.resize((SIZE, SIZE), Image.LANCZOS)
        return im.copy()


def placeholder_image(key: str) -> Image.Image:
    color = PLACEHOLDER_COLOR[key]
    rgb = tuple(int(color[i:i + 2], 16) for i in (1, 3, 5))
    return Image.new("RGB", (SIZE, SIZE), rgb)


def to_data_url(image: Image.Image) -> str:
    buffer = io.BytesIO()
    image.save(buffer, format="PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buffer.getvalue()).decode("ascii")


def wrap(data_url: str, indent: str, width: int = 96) -> str:
    """Concatenate a long data URL over several lines so the source stays readable."""
    head, payload = data_url.split(",", 1)
    chunks = [head + ","]
    for index in range(0, len(payload), width):
        chunks.append(payload[index:index + width])
    return (" +\n" + indent).join("'" + chunk + "'" for chunk in chunks)


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    urls: dict[str, str] = {}
    placeholders: list[str] = []
    for key in KEYS:
        source = ORIGINALS / f"{key}.png"
        if source.exists():
            image = square_resize(source)
            target = OUT_DIR / f"{key}.png"
            image.save(target, format="PNG", optimize=True)
            urls[key] = to_data_url(image)
            print(f"  {key:<7} {source.name} {source.stat().st_size // 1024} KiB -> "
                  f"src/avatars/{key}.png {target.stat().st_size // 1024} KiB, data URL {len(urls[key]) // 1024} KiB")
        else:
            urls[key] = to_data_url(placeholder_image(key))
            placeholders.append(key)
            print(f"  {key:<7} 原图缺失 -> 占位色 {PLACEHOLDER_COLOR[key]} (TODO 待终稿替换)")

    # 1. src/avatars.js — the canonical module.
    lines = [
        "// GENERATED by src/build_avatars.py — do not edit by hand.",
        "// 128x128 avatars downscaled from docs/images/avatars/*.png (originals are 512x512).",
        "// Re-run: python3 src/build_avatars.py",
        "",
    ]
    for key in KEYS:
        lines.append(f"export const {key} = {wrap(urls[key], '    ')};")
    lines += [
        "",
        f"export const AVATARS = {{ {', '.join(KEYS)} }};",
        f"export const PLACEHOLDERS = [{', '.join(repr(k) for k in placeholders)}];"
        if placeholders else "export const PLACEHOLDERS = [];",
        "export default AVATARS;",
        "",
    ]
    AVATARS_JS.write_text("\n".join(lines), encoding="utf-8")
    print(f"  wrote {AVATARS_JS.relative_to(PKG)} ({AVATARS_JS.stat().st_size // 1024} KiB)")

    # 2. client.js — rewrite the generated region only.
    client = CLIENT_JS.read_text(encoding="utf-8")
    if REGION_START not in client or REGION_END not in client:
        print("  ERROR: client.js avatar region markers missing", file=sys.stderr)
        return 1
    before, rest = client.split(REGION_START, 1)
    _, after = rest.split(REGION_END, 1)
    body = "\n".join(
        [REGION_START]
        + ["\t\tconst AVATARS = {"]
        + [f"\t\t\t{key}: {wrap(urls[key], chr(9) * 4)}," for key in KEYS]
        + ["\t\t};"]
        + [f"\t\tconst AVATAR_PLACEHOLDERS = [{', '.join(repr(k) for k in placeholders)}];" if placeholders
           else "\t\tconst AVATAR_PLACEHOLDERS = [];"]
        + ["\t\t" + REGION_END]
    )
    CLIENT_JS.write_text(before + body + after, encoding="utf-8")
    print(f"  rewrote {CLIENT_JS.name} avatars region; "
          f"placeholders={placeholders or 'none'}")
    print("  next: node --check client.js src/avatars.js")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
